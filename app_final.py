def compute_pss10(answers: list) -> int:
    """answers: 10 values from 0 to 4, in question order (items 1 to 10)."""
    total = 0
    for i, value in enumerate(answers, start=1):
        total += (4 - value) if i in PSS10_REVERSED_ITEMS else value
    return total


def compute_mqs(answers: list) -> int:
    """answers: values 1-7 in the same order as MQS_ITEMS.
    Negative items are reversed so that, in the total, a high value = favorable result."""
    total = 0
    for (_question, positive), value in zip(MQS_ITEMS, answers):
        total += value if positive else (8 - value)   # reversal: 1↔7, 2↔6, 3↔5, 4↔4
    return total


def mqs_range() -> tuple:
    """(minimum, maximum) possible MQS score."""
    return len(MQS_ITEMS), 7 * len(MQS_ITEMS)


def _ovulation_window(cycle_length: int, period_length: int) -> tuple:
    start = max(cycle_length - 16, period_length + 3)
    end = min(cycle_length - 11, start + 4)
    return start, end


def compute_phase(day: int, cycle_length: int, period_length: int) -> int:
    """Return the phase index: 0 menstrual, 1 follicular, 2 ovulatory, 3 luteal."""
    day_in_cycle = day % cycle_length if cycle_length > 0 else day
    ov_start, ov_end = _ovulation_window(cycle_length, period_length)
    if day_in_cycle <= period_length:
        return 0
    if day_in_cycle < ov_start:
        return 1
    if day_in_cycle <= ov_end:
        return 2
    return 3


