def _adjustment_lines(items) -> list:
    """Rebuild the adjustment explanations in the current language from (key, params) pairs."""
    lines = []
    for key, params in items:
        params = dict(params)
        if key == "adj_mood":
            params["value"] = label(params["value"])
        lines.append(t(key, **params))
    return lines


def _render_prediction(result) -> None:
    """Result panel of the latest calculation (kept in session_state, so it survives reruns)."""
    if not result or result.get("username") != st.session_state.username:
        return
    phase_name = result["phase_name"]
    phase_index = result["phase_index"]
    model_score = result["model_score"]
    predicted_score = result["predicted_score"]
    total_adjustment = result["total_adjustment"]
    adjustment_details = _adjustment_lines(result["adjustments"])
    style = PHASE_STYLE[phase_name]

    col_gauge, col_phase = st.columns([1, 1.4])
    with col_gauge:
        with st.container(border=True):
            st.markdown(
                render_gauge(predicted_score, style["color"], t("gauge_today")),
                unsafe_allow_html=True,
            )
    with col_phase:
        with st.container(border=True):
            adjustment_note = t("daily_adjustment", adj=f"{total_adjustment:+.1f}") if adjustment_details else ""
            st.markdown(f"""
            <div style="font-family:'Figtree',sans-serif; font-weight:700; color:{style['color']} !important;
                         font-size:0.72rem; ">
                {style['emoji']} {t("phase_detected")}
            </div>
            <div style="font-family:'Bricolage Grotesque',sans-serif; font-size:1.8rem; color:#111111 !important; margin-top:0.1rem;">
                {label(phase_name)}
            </div>
            <div style="font-size:0.85rem; color:#5B5B5B !important; margin-top:0.5rem;">
                {t("base_score", score=f"{model_score:.1f}")}
                {adjustment_note}
            </div>
            """, unsafe_allow_html=True)

    st.write("")
    st.markdown(
        render_cycle_timeline(result["cycle_day"], result["avg_cycle_length"], result["period_length"]),
        unsafe_allow_html=True,
    )
    st.write("")

    if adjustment_details:
        col_a, col_b = st.columns(2)
        col_a.metric(label=t("metric_base"), value=f"{model_score:.1f} / 10.0")
        col_b.metric(
            label=t("metric_adjusted"),
            value=f"{predicted_score:.1f} / 10.0",
            delta=f"{total_adjustment:+.1f}",
        )
        with st.expander(t("adj_details")):
            for line in adjustment_details:
                st.markdown(f"- {line}")
    else:
        st.caption(t("tip_checkin"))

    st.markdown("---")
    st.markdown(t("prescription_title"))

    level = "low" if predicted_score < 5 else "high"
    show = getattr(st, REC_KIND[(phase_index, level)])
    show(t(f"rec_{phase_index}_{level}"))


@st.fragment
def render_readiness_tab(username: str):
    model, scaler, feature_cols, model_error = load_model_artifacts()
    if model_error:
        st.error(t("err_model_load", error=model_error, dir=ARTIFACTS_DIR))

    col1, col2 = st.columns(2)

    with col1:
        with st.container(border=True):
            st.markdown(t("profile_title"))
            age = st.number_input(t("age"), min_value=11, max_value=80, value=25, key="age")
            height_m = st.number_input(t("height"), min_value=1.40, max_value=2.20, value=1.65, step=0.01, key="height_m")
            weight_kg = st.number_input(t("weight"), min_value=40.0, max_value=150.0, value=65.0, step=0.1, key="weight_kg")
            bmi = weight_kg / (height_m ** 2)
            st.info(t("bmi_calculated", bmi=f"{bmi:.1f}"))
            injury_pain = st.slider(t("pain_scale"), 0, 10, 0, key="injury_pain")

    with col2:
        with st.container(border=True):
            st.markdown(t("cycle_title"))
            cycle_day = st.number_input(t("cycle_day"), min_value=0, max_value=40, value=14, key="cycle_day")
            avg_cycle_length = st.number_input(t("cycle_length"), min_value=20, max_value=40, value=28, key="cycle_length")
            period_length = st.number_input(t("period_length"), min_value=1, max_value=10, value=5, key="period_length")

            regularity = st.selectbox(t("cycle_regular"), ["regular", "irregular"], format_func=label, key="regularity")
            contraceptive = st.selectbox(t("contraceptive"), ["no", "yes"], format_func=label, key="contraceptive")

    with st.container(border=True):
        st.markdown(t("exercise_title"))
        weekly_frequency = st.slider(t("weekly_frequency"), 1, 7, 3, key="weekly_frequency")
        workout_duration = st.slider(t("workout_duration"), 0, 240, 60, step=5, key="workout_duration")

    st.write("")

    # ── Prediction ──
    if st.button(t("calc_btn"), width="stretch", type="primary"):

        if model is None:
            st.warning(t("warn_model_not_loaded"))
            return

        phase_index = compute_phase(cycle_day, avg_cycle_length, period_length)
        phase_name = PHASES[phase_index]

        # Keys below are the Portuguese feature names the model was trained with — do not rename.
        input_data = {
            "IDADE_CRONOLOGICA": age,
            "IMC": bmi,
            "ESTATURA_M": height_m,
            "MASSA_CORPORAL_KG": weight_kg,
            "dia_ciclo": cycle_day,
            "duracao_ciclo_media": avg_cycle_length,
            "QUANTOS_DIAS_DUROU_SUA_ULTIMA_MENSTRUACAO": period_length,
            "SEU_CICLO_E_REGULAR_OU_IRREGULAR_enc": 1 if regularity == "regular" else 0,
            "USA_ALGUM_METODO_CONTRACEPTIVO_HORMONAL_enc": 1 if contraceptive == "yes" else 0,
            "POSSUI_ALGUMA_LESAO_OU_RESTRICAO_MUSCULOESQUELETICO_enc": 1 if injury_pain >= 5 else 0,
            "QUAL_FREQUENCIA_QUE_VOCE_PRATICA_ESSE_EXERCICIO": weekly_frequency,
            # NOTE: kept exactly as in the original code (the value is multiplied by 60).
            # Confirm this matches the unit used when the model was trained.
            "EM_MEDIA_QUAL_A_DURACAO_DO_SEU_TREINO_EM_MINUTOS": workout_duration * 60,
            "fase_ciclo": phase_index,
            "COMO_E_SEU_FLUXO_MENSTRUAL_enc": 1,
        }

        df_input = pd.DataFrame([input_data])

        for col in feature_cols:
            if col not in df_input.columns:
                df_input[col] = 0.0
        df_input = df_input[feature_cols]

        # Scale using the names the scaler learned at fit time (DataFrame),
        # with a positional fallback if the scaler was fitted without names.
        if hasattr(scaler, "feature_names_in_"):
            df_scaled = df_input.copy()
            scaler_cols = list(scaler.feature_names_in_)
            df_scaled[scaler_cols] = scaler.transform(df_input[scaler_cols])
            X_scaled = df_scaled.values
        else:
            X_scaled = scaler.transform(df_input.values)

        raw_score = model.predict(X_scaled)[0]
        model_score = max(0.0, min(10.0, raw_score))

        # ── Rule-based adjustment using today's check-in / PSS-10 / MQS (when available) ──
        # The ML model was trained only on profile + cycle phase (the dataset has no real
        # historical PSS-10/MQS data). So this adjustment is rule-based, not learned — until
        # enough real check-ins accumulate to include them when retraining with pipeline_final.py.
        total_adjustment = 0.0
        adjustments = []   # (translation key, params) — rendered in the current language on display

        today_checkin = get_today_checkin(username)
        if today_checkin:
            if today_checkin["pain"] >= 5:
                total_adjustment -= 1.0
                adjustments.append(("adj_pain", {"value": today_checkin["pain"]}))
            if today_checkin["energy"] <= 3:
                total_adjustment -= 1.0
                adjustments.append(("adj_energy_low", {"value": today_checkin["energy"]}))
            elif today_checkin["energy"] >= 8:
                total_adjustment += 0.5
                adjustments.append(("adj_energy_high", {"value": today_checkin["energy"]}))
            if today_checkin["mood"] in LOW_MOOD_VALUES:
                total_adjustment -= 0.5
                adjustments.append(("adj_mood", {"value": today_checkin["mood"]}))

        latest_pss10 = get_latest_pss10(username)
        if latest_pss10:
            if latest_pss10["total_score"] >= 27:
                total_adjustment -= 1.5
                adjustments.append(("adj_pss_high", {"value": latest_pss10["total_score"]}))
            elif latest_pss10["total_score"] <= 13:
                total_adjustment += 0.5
                adjustments.append(("adj_pss_low", {"value": latest_pss10["total_score"]}))

        latest_mqs = get_latest_mqs(username)
        if latest_mqs:
            mqs_min, mqs_max = mqs_range()
            mqs_span = mqs_max - mqs_min
            if latest_mqs["total_score"] <= mqs_min + mqs_span * 0.33:
                total_adjustment -= 1.0
                adjustments.append(("adj_mqs_low", {"value": latest_mqs["total_score"], "max": mqs_max}))
            elif latest_mqs["total_score"] >= mqs_min + mqs_span * 0.66:
                total_adjustment += 0.5
                adjustments.append(("adj_mqs_high", {"value": latest_mqs["total_score"], "max": mqs_max}))

        predicted_score = max(0.0, min(10.0, model_score + total_adjustment))

        try:
            save_record(username, phase_name, predicted_score)
        except Exception as e:
            diag = getattr(e, "diag", None)
            st.error(f"{type(e).__name__}: {getattr(diag, 'message_primary', None) or e}")
            st.code(f"schema={getattr(diag, 'schema_name', None)} | "
                    f"table={getattr(diag, 'table_name', None)} | "
                    f"context={getattr(diag, 'context', None)}")
            st.stop()
        st.session_state["last_prediction"] = {
            "username": username, "phase_name": phase_name, "phase_index": phase_index,
            "model_score": float(model_score), "predicted_score": float(predicted_score),
            "total_adjustment": total_adjustment, "adjustments": adjustments,
            "cycle_day": cycle_day, "avg_cycle_length": avg_cycle_length, "period_length": period_length,
        }
        st.rerun()   # full rerun: sidebar, accent color and dashboard pick up the new record

    _render_prediction(st.session_state.get("last_prediction"))


