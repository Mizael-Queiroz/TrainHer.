@st.cache_resource(show_spinner=False)
def _logo_assets(path_str: str, max_width: int):
    """(base64 JPEG downscaled to max_width, background color of the logo) — computed once per process."""
    try:
        im = Image.open(path_str).convert("RGB")
        w, h = im.size
        px = [im.getpixel(p) for p in ((2, 2), (w - 3, 2), (2, h - 3), (w - 3, h - 3))]
        bg = "#%02X%02X%02X" % tuple(sum(c[i] for c in px) // 4 for i in range(3))
        if w > max_width:
            im = im.resize((max_width, round(h * max_width / w)), Image.LANCZOS)
        buf = io.BytesIO()
        im.save(buf, "JPEG", quality=88, optimize=True)
        return base64.b64encode(buf.getvalue()).decode(), bg
    except Exception:
        return "", None


def _logo_width(path: Path) -> int:
    return 640 if Path(path) == LOGO_FULL_PATH else 360


def logo_b64(path: Path = LOGO_HEADER_PATH) -> str:
    """Logo as base64 for embedding in HTML (empty string if the file is missing)."""
    return _logo_assets(str(path), _logo_width(path))[0]


def logo_bg(path: Path, fallback: str = "#ECE8F0") -> str:
    """Background color of a logo image, so the logo sits on a seamless panel."""
    return _logo_assets(str(path), _logo_width(path))[1] or fallback


