@st.cache_data(ttl=60, show_spinner=False)
def export_anonymized_zip(salt: str, lang: str):
    """ZIP of anonymized CSVs, only for users who consented. Returns (bytes, n_participants)."""
    consenting = read_df("SELECT username FROM users WHERE consentimento_pesquisa = 1")["username"].tolist()
    codes = {u: hashlib.sha256((salt + u).encode("utf-8")).hexdigest()[:12] for u in consenting}

    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as z:
        for table in EXPORT_TABLES:
            df = read_df(f"SELECT * FROM {table}")
            df = df[df["username"].isin(consenting)].copy()
            df.insert(0, "participante", df["username"].map(codes))
            df = df.drop(columns=["username"])
            z.writestr(f"{table}.csv", df.to_csv(index=False))
        z.writestr("README.txt", t("export_readme", when=f"{datetime.datetime.now():%Y-%m-%d %H:%M:%S}",
                                   n=len(consenting)))
    return buffer.getvalue(), len(consenting)


