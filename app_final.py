# ── Recovery code (shown once; only its PBKDF2 hash is stored) ──
def _new_recovery_code() -> str:
    raw = secrets.token_hex(8).upper()                       # 64 bits
    return "-".join(raw[i:i + 4] for i in range(0, 16, 4))


def _normalize_code(code: str) -> str:
    return code.replace("-", "").replace(" ", "").upper()


def set_recovery_code(username: str) -> str:
    """Generate and store a new recovery code (invalidates the previous one). Returns it once."""
    code = _new_recovery_code()
    with get_conn() as conn:
        conn.cursor().execute("UPDATE users SET recovery_hash=? WHERE username=?",
                              (_hash_password(_normalize_code(code)), username))
        conn.commit()
    return code


def reset_password_with_code(username: str, code: str, new_password: str):
    """Returns a NEW recovery code on success (the used one is consumed), or None."""
    if not username or username.startswith("google_"):
        return None
    with get_conn() as conn:
        c = conn.cursor()
        c.execute("SELECT recovery_hash FROM users WHERE username=?", (username,))
        row = c.fetchone()
        stored = row[0] if row else None
        if not stored or not stored.startswith("pbkdf2$"):
            return None
        _, salt_hex, _ = stored.split("$")
        candidate = _hash_password(_normalize_code(code), bytes.fromhex(salt_hex))
        if not hmac.compare_digest(candidate, stored):
            return None
        new_code = _new_recovery_code()
        c.execute("UPDATE users SET password=?, recovery_hash=? WHERE username=?",
                  (_hash_password(new_password), _hash_password(_normalize_code(new_code)), username))
        conn.commit()
    return new_code


def add_user(username, password, research_consent=False):
    """Returns the recovery code (str) on success, None if the username already exists."""
    code = _new_recovery_code()
    try:
        with get_conn() as conn:
            conn.cursor().execute(
                "INSERT INTO users (username, password, consentimento_pesquisa, consentimento_data, "
                "consentimento_versao, recovery_hash) VALUES (?, ?, ?, ?, ?, ?)",
                (username, _hash_password(password), 1 if research_consent else 0,
                 _now() if research_consent else None,
                 CONSENT_VERSION if research_consent else None,
                 _hash_password(_normalize_code(code))),
            )
            conn.commit()
        return code
    except _integrity_errors():
        return None


