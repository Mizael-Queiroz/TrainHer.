def _slider_color_rules(label_key: str, color: str) -> str:
    """CSS rules that color one slider (found by its aria-label) in every supported language."""
    rules = []
    for code in LANGUAGES:
        selector = f'.stApp [data-testid="stSlider"]:has([aria-label="{TEXTS[code][label_key]}"])'
        rules.append(
            f'{selector} [data-baseweb="slider"] > div > div:nth-child(2) {{ background: {color} !important; }}\n'
            f'{selector} [role="slider"] {{ background: {color} !important; }}'
        )
    return "\n".join(rules)


