"""
TrainHer — single-file Streamlit app
====================================
Cycle-aware training readiness: ML model + daily check-ins + PSS-10 + MQS.
Multilingual interface (Portuguese / English / Spanish), selectable by the user.
Sign-in with username/password or with a Google account (Streamlit native OIDC).

Expected artifacts (generated by pipeline_final.py) in ./artefatos/:
  - modelo_campeao.joblib   trained model
  - scaler.joblib           StandardScaler fitted on a DataFrame
  - feature_cols.csv        feature names, in training order

Google sign-in needs `Authlib` installed and an [auth] / [auth.google] section
in the Streamlit secrets (see README / secrets example).

Security / LGPD features
------------------------
- Per-account administrators (users.is_admin = 1, set via SQL); no shared admin password.
- Password recovery through a one-time recovery code shown at sign-up.
- Minimum password length (MIN_PASSWORD_LEN).
- In-app research-consent withdrawal and full account + data deletion.
- Daily SQLite backup (Postgres: use the provider's backups + backup_pg.sh).
- Admin monitoring panel (memory, sessions, database connections).

Conventions
-----------
- Model feature names are the original Portuguese column names used at training
  time (e.g. "IDADE_CRONOLOGICA"). Do not rename them.
- Database table/column names (registros, checkins_diarios, fase, dor, ...) are kept
  in Portuguese so existing databases and previously exported data keep working.
- Values stored in the database (phases, mood, sleep, flow) are canonical Portuguese
  keys; they are translated only when displayed (see VALUE_LABELS / label()).
"""

