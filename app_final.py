def _memory_mb():
    try:
        import psutil
        return psutil.Process().memory_info().rss / 1e6
    except Exception:
        try:
            with open("/proc/self/status") as f:
                for line in f:
                    if line.startswith("VmRSS:"):
                        return int(line.split()[1]) / 1024
        except Exception:
            pass
    return None


def _active_sessions():
    try:                                    # internal Streamlit API: may change between versions
        from streamlit.runtime import get_instance
        return len(get_instance()._session_mgr.list_active_sessions())
    except Exception:
        return None


def system_stats() -> dict:
    stats = {"memory_mb": _memory_mb(), "sessions": _active_sessions(), "pool_in_use": None,
             "db_connections": None, "db_max": None}
    with get_conn() as conn:
        c = conn.cursor()
        c.execute("SELECT count(*) FROM users")
        stats["users"] = c.fetchone()[0]
        if USE_PG:
            c.execute("SELECT count(*) FROM pg_stat_activity WHERE datname = current_database()")
            stats["db_connections"] = c.fetchone()[0]
            c.execute("SHOW max_connections")
            stats["db_max"] = int(c.fetchone()[0])
            stats["pool_in_use"] = len(getattr(_pg_pool(), "_used", {}))   # private attr of psycopg2 pool
    return stats


@st.cache_resource(show_spinner=False)
def _backup_state() -> dict:
    return {"day": None}


def run_daily_backup() -> None:
    """SQLite only: one consistent snapshot per day, last BACKUP_KEEP kept.
    With Postgres, backups are the provider's job (see backup_pg.sh)."""
    if USE_PG:
        return
    state, today = _backup_state(), datetime.date.today().isoformat()
    if state["day"] == today:
        return
    try:
        BACKUP_DIR.mkdir(exist_ok=True)
        dest = BACKUP_DIR / f"cycletrain_{today}.db"
        if not dest.exists():
            src, dst = sqlite3.connect(DB_PATH), sqlite3.connect(dest)
            with dst:
                src.backup(dst)
            src.close()
            dst.close()
        for old in sorted(BACKUP_DIR.glob("cycletrain_*.db"))[:-BACKUP_KEEP]:
            old.unlink()
        state["day"] = today
    except Exception:
        pass                                # a backup problem must never break the app


